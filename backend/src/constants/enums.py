from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class RunStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class StepStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    completed = 'completed'
    reused = 'reused'
    failed = 'failed'
class StepKind(str, Enum):
    source = 'source'
    filter_halt = 'filter_halt'
    merge = 'merge'
    join_temp = 'join_temp'
